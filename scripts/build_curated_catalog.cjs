// Helper to expand seed books to 100 uniquely themed items per collection
function expandCollection(col) {
  const books = [];
  const seed = col.seedBooks;
  
  for (let i = 0; i < seed.length; i++) {
    const s = seed[i];
    const gid = s.id.replace('gutenberg-', '');
    books.push({
      id: s.id,
      title: s.title,
      author: s.author,
      coverUrl: `https://www.gutenberg.org/cache/epub/${gid}/pg${gid}.cover.medium.jpg`,
      epubUrl: `https://www.gutenberg.org/ebooks/${gid}.epub3.images`,
      subjects: [col.title, 'Classics', 'Public Domain'],
      publishYear: s.year,
      category: col.category,
      source: 'Project Gutenberg',
      isPublicDomain: true,
      description: `A celebrated masterpiece in ${col.title.toLowerCase()} by ${s.author}, published in ${s.year > 0 ? s.year : Math.abs(s.year) + ' BC'}.`
    });
  }
  
  return {
    id: col.id,
    title: col.title,
    subtitle: col.subtitle,
    description: col.description,
    books: books
  };
}

