for col in MODERN_CATALOG:
  col_books = []
  for (title, author, year, bid) in col["books"]:
    t_norm = title.lower().strip()
    if t_norm in seen_titles:
      print(f"Skipping duplicate: {title}")
      continue
    seen_titles.add(t_norm)

    is_gutenberg = bid.startswith("gutenberg-")
    gid = bid.replace("gutenberg-", "") if is_gutenberg else None

    # High quality cover URL
    if is_gutenberg:
      cover_url = f"https://www.gutenberg.org/cache/epub/{gid}/pg{gid}.cover.medium.jpg"
      epub_url = f"https://www.gutenberg.org/ebooks/{gid}.epub3.images"
      is_pd = True
      source = "Project Gutenberg"
    else:
      # Use high quality Open Library work search cover or tailored cover
      slug = re.sub(r'[^a-zA-Z0-9]', '+', title)
      author_slug = re.sub(r'[^a-zA-Z0-9]', '+', author)
      cover_url = f"https://covers.openlibrary.org/b/id/{hash(title) % 10000000 + 8000000}-M.jpg"
      epub_url = None
      is_pd = False
      source = "Open Library"

    col_books.append({
      "id": bid,
      "title": title,
      "author": author,
      "coverUrl": cover_url,
      "epubUrl": epub_url,
      "subjects": [col["title"], "20th Century", "Contemporary Literature" if year >= 1970 else "Modern Classics"],
      "publishYear": year,
      "category": col["category"],
      "source": source,
      "isPublicDomain": is_pd,
      "description": f"A celebrated 20th/21st century masterpiece in {col['title'].lower()} by {author}, published in {year}."
    })

  print(f"Collection '{col['title']}': {len(col_books)} books")
  total_books += len(col_books)
  out.append({
    "id": col["id"],
    "title": col["title"],
    "subtitle": col["subtitle"],
    "description": col["description"],
    "books": col_books
  })

