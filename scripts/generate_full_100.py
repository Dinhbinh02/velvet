out = []
seen_titles = set()
total_books = 0

for col in COLLECTIONS_DATA:
  col_books = []
  for (title, author, year, gid) in col["books"]:
    t_norm = title.lower().strip()
    if t_norm in seen_titles:
      print(f"Skipping duplicate across collections: {title}")
      continue
    seen_titles.add(t_norm)
    
    col_books.append({
      "id": f"gutenberg-{gid}",
      "title": title,
      "author": author,
      "coverUrl": f"https://www.gutenberg.org/cache/epub/{gid}/pg{gid}.cover.medium.jpg",
      "epubUrl": f"https://www.gutenberg.org/cache/epub/{gid}/pg{gid}-images.epub",
      "subjects": [col["title"], "Classics", "Public Domain"],
      "publishYear": year,
      "category": col["category"],
      "source": "Project Gutenberg",
      "isPublicDomain": True,
      "description": f"A celebrated masterpiece in {col['title'].lower()} by {author}, published in {year if year > 0 else str(abs(year)) + ' BC'}."
    })

  print(f"Collection '{col['title']}': {len(col_books)} books")
  total_books += len(col_books)
  out.append({
    "id": col["id"],
    "title": col["title"],
    "subtitle": col["subtitle"],
    "description": col["description"],
    "books": col_books
  })

dest = os.path.abspath("src/data/curated_collections_100.json")
with open(dest, "w", encoding="utf-8") as f:
  json.dump(out, f, indent=2, ensure_ascii=False)

print(f"\n🎉 Successfully compiled {len(out)} collections with {total_books} strictly unique 100-book catalogs to {dest}!")
